def square_layers(n_layers=10, size=40.0, feed=60.0, h=0.2):
    lines = ["G21", "G90", "M83", "G92 E0", f"G1 Z{h} F600"]
    e_per_mm = 0.033
    for i in range(n_layers):
        z = h * (i + 1)
        lines.append(f"G1 Z{z:.2f} F600")
        lines.append(f"G0 X0 Y0 F{feed * 60 * 2}")
        for x, y in ((size, 0), (size, size), (0, size), (0, 0)):
            lines.append(f"G1 X{x} Y{y} E{size * e_per_mm:.4f} F{feed * 60}")
    return "\n".join(lines) + "\n"


def test_simulation_square():
    text = square_layers()
    lim = MachineLimits(accel=1000, max_velocity=300, square_corner_velocity=5)
    r = GcodeAnalyzer(limits=lim, heating_estimates=False).analyze_stream(io.StringIO(text))
    assert r.time_source == "simulation"
    assert r.layers == 10
    # 10 слоёв × 160 мм при 60 мм/с ≈ 26.7 с + разгоны/повороты + подъёмы Z
    assert 26 < r.sim_time_s < 40, r.sim_time_s
    assert math.isclose(r.filament_mm, 10 * 4 * 40 * 0.033, rel_tol=1e-3)
    assert r.bbox_max[0] == 40 and r.bbox_max[1] == 40
    assert len(r.layer_times) == 10 and r.layer_times == sorted(r.layer_times)


def test_absolute_e_and_retract():
    text = "M82\nG92 E0\nG1 X10 E1 F1200\nG1 E0.2 F2400\nG1 X20 F6000\nG1 E1 F2400\nG1 X30 E2 F1200\n"
    r = run(text, heating_estimates=False)
    # 1 мм + (-0.8 ретракт) + 0.8 возврат + 1 мм = 2 мм
    assert math.isclose(r.filament_mm, 2.0, abs_tol=1e-6)


def test_more_accel_is_faster():
    text = square_layers(n_layers=5, size=10, feed=200)
    slow = GcodeAnalyzer(limits=MachineLimits(accel=500), heating_estimates=False).analyze_stream(io.StringIO(text))
    fast = GcodeAnalyzer(limits=MachineLimits(accel=10000), heating_estimates=False).analyze_stream(io.StringIO(text))
    assert fast.sim_time_s < slow.sim_time_s


def test_m204_changes_accel():
    base = square_layers(n_layers=3, size=10, feed=200)
    a = run(base, heating_estimates=False)
    b = run("M204 S20000\n" + base, heating_estimates=False)
    assert b.sim_time_s < a.sim_time_s


def test_arc_length():
    # полукруг радиусом 10: длина 31.4 мм при 10 мм/с ≈ 3.1 с (+разгон)
    text = "G90\nM83\nG1 X0 Y0 F600\nG2 X20 Y0 I10 J0 E1 F600\n"
    r = run(text, heating_estimates=False, limits=MachineLimits(accel=100000))
    assert 3.0 < r.sim_time_s < 3.5, r.sim_time_s
