import trimesh

from printhub.app import create_app

from printhub.emulators import MoonrakerPrinter, free_port, serve_app

GCODE = """; generated by OrcaSlicer 2.3.0
; estimated printing time (normal mode) = 1h 0m 0s
; total filament used [g] = 10.00
; filament used [mm] = 3300.00
; filament_type = PLA
G90
M83
G1 X10 Y10 E1 F1200
"""


async def wait_until(fn, timeout=8.0):
    loop = asyncio.get_running_loop()
    end = loop.time() + timeout
    while True:
        r = await fn()
        if r:
            return r
        if loop.time() > end:
            raise AssertionError("не дождались")
        await asyncio.sleep(0.1)


async def test_full_flow(tmp_path):
    pr = MoonrakerPrinter()
    await pr.start()
    app = create_app(str(tmp_path / "data"))
    port = free_port()
    import uvicorn
    server = uvicorn.Server(uvicorn.Config(app, host="127.0.0.1", port=port, log_level="warning"))
    task = asyncio.create_task(server.serve())
    while not server.started:
        await asyncio.sleep(0.05)
    base = f"http://127.0.0.1:{port}/api"
    try:
        async with httpx.AsyncClient(base_url=base, timeout=20) as c:
            assert (await c.get("/info")).status_code == 200
            kinds = {d["kind"] for d in (await c.get("/drivers")).json()}
            assert {"bambu", "elegoo_sdcp", "elegoo_cc2", "anycubic_lan", "anycubic_photon", "moonraker", "octoprint"} <= kinds

            r = await c.post("/printers", json={"kind": "moonraker", "host": "127.0.0.1", "port": pr.port, "name": "Neptune",
                                                "build_volume": [225, 225, 265], "power_w": 150})
            assert r.status_code == 200, r.text
            pid = r.json()["config"]["id"]

            async def idle():
                ps = (await c.get("/printers")).json()
                return ps[0]["status"]["state"] == "idle"
            await wait_until(idle)

            # проверка соединения
            t = (await c.post("/printers/test", json={"kind": "moonraker", "host": "127.0.0.1", "port": pr.port})).json()
            assert t["ok"] and t["hostname"] == "neptune4"

            # библиотека: G-code
            r = await c.post("/library", files={"file": ("cube.gcode", GCODE.encode(), "text/plain")})
            item = r.json()
            assert item["kind"] == "gcode" and item["summary"]["time_s"] == 3600 and item["summary"]["material_g"] == 10

            # материал и тариф
            mats = (await c.get("/materials")).json()
            pla = next(m for m in mats if m["type"] == "PLA")
            await c.put("/settings", json={"electricity_price": 10, "failure_pct": 0})
            est = (await c.post("/estimate", json={"library_id": item["id"], "material_id": pla["id"], "printer_id": pid})).json()
            # 10 г × 1500/кг = 15 + 0.15 кВт·ч × 10 = 1.5
            assert est["cost"]["material_cost"] == 15.0 and est["cost"]["electricity_cost"] == 1.5 and est["cost"]["total"] == 16.5

            # отправка и запуск
            r = await c.post(f"/library/{item['id']}/send", json={"printer_id": pid, "start": True, "material_id": pla["id"]})
            assert r.status_code == 200, r.text

            async def printing():
                ps = (await c.get("/printers")).json()
                return ps[0]["status"]["state"] == "printing"
            await wait_until(printing)
            assert "start:cube.gcode" in pr.calls
            jobs = (await c.get("/jobs")).json()
            assert jobs[0]["status"] == "printing" and jobs[0]["library_id"] == item["id"]

            # пауза через API
            assert (await c.post(f"/printers/{pid}/action", json={"action": "pause"})).status_code == 200
            assert "pause" in pr.calls

            # завершение печати на принтере
            await pr.notify({"print_stats": {"state": "complete"}, "display_status": {"progress": 1.0}})

            async def finished():
                j = (await c.get("/jobs")).json()[0]
                return j if j["status"] == "finished" else None
            job = await wait_until(finished)
            assert job["material_g"] == 10 and job["cost"] is not None
            mat_after = next(m for m in (await c.get("/materials")).json() if m["id"] == pla["id"])
            assert mat_after["remaining_g"] == pla["remaining_g"] - 10
            stats = (await c.get("/stats")).json()
            assert stats["total"]["finished"] == 1

            # очередь с автозапуском после «стол очищен»
            q = (await c.post("/queue", json={"library_id": item["id"], "printer_id": pid, "auto_start": True})).json()
            assert q["id"]
            pr.calls.clear()
            await c.post(f"/printers/{pid}/action", json={"action": "ready", "value": True})

            async def started_again():
                return any(x.startswith("start:") for x in pr.calls)
            await wait_until(started_again)

            # файлы на принтере
            files = (await c.get(f"/printers/{pid}/files")).json()
            assert files[0]["name"] == "cube.gcode"

            # 3D-модель: битая → ремонт → оценка
            box = trimesh.creation.box((20, 20, 20))
            side = box.face_normals[:, 0] < -0.99  # обе грани одной стороны куба
            broken = trimesh.Trimesh(box.vertices, box.faces[~side], process=False)
            stl = broken.export(file_type="stl")
            r = await c.post("/library", params={"printer_id": pid}, files={"file": ("box.stl", stl, "model/stl")})
            mesh_item = r.json()
            assert mesh_item["kind"] == "mesh"
            rep = (await c.post(f"/library/{mesh_item['id']}/mesh/analyze", json={"printer_id": pid})).json()
            assert not rep["watertight"] and not rep["printable"]
            fix = (await c.post(f"/library/{mesh_item['id']}/mesh/repair", json={"printer_id": pid})).json()
            assert fix["after"]["watertight"] and fix["after"]["printable"]
            assert abs(fix["after"]["volume_cm3"] - 8.0) < 0.01
            tr = (await c.post(f"/library/{fix['item_id']}/mesh/transform", json={"ops": [{"op": "scale", "value": 2}], "printer_id": pid})).json()
            assert tr["mesh"]["size_mm"] == [40.0, 40.0, 40.0]
            stl_bytes = (await c.get(f"/library/{tr['item_id']}/mesh.stl")).content
            assert len(stl_bytes) > 84
            est = (await c.post("/estimate", json={"library_id": tr["item_id"], "technology": "resin"})).json()
            assert est["estimate"]["layers"] == 800 and est["cost"]["total"] >= 0
            orients = (await c.get(f"/library/{tr['item_id']}/mesh/orientations")).json()
            assert orients and "matrix" in orients[0]
            # отправить 3D-модель на печать нельзя — понятная ошибка
            r = await c.post(f"/library/{tr['item_id']}/send", json={"printer_id": pid})
            assert r.status_code == 400 and "Нарежьте" in r.json()["detail"]

            # веб-интерфейс отдаётся
            async with httpx.AsyncClient(timeout=5) as c2:
                html = (await c2.get(f"http://127.0.0.1:{port}/")).text
                assert "SEBE 3D" in html
    finally:
        server.should_exit = True
        await task
        await pr.stop()
