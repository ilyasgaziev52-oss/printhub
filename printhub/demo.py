def sample_gcode(size: float = 20.0, layers: int = 100, h: float = 0.2) -> str:
    """Простой «кубик» с заголовком в стиле OrcaSlicer."""
    e_mm = 0.0333
    lines = ["; generated by OrcaSlicer 2.5.0 (PrintHub demo)", "; printer_model = Elegoo Centauri Carbon",
             "; filament_type = PLA", "; filament_density = 1.24", "; layer_height = 0.2", "G21", "G90", "M83",
             "M140 S60", "M104 S215", "M190 S60", "M109 S215", "G28", "G92 E0"]
    total_e = 0.0
    cx = cy = 128.0
    for i in range(layers):
        z = h * (i + 1)
        lines.append(";LAYER_CHANGE")
        lines.append(f"G1 Z{z:.2f} F600")
        for k in range(3):  # три периметра
            off = size / 2 - k * 0.45
            pts = [(cx - off, cy - off), (cx + off, cy - off), (cx + off, cy + off), (cx - off, cy + off), (cx - off, cy - off)]
            lines.append(f"G0 X{pts[0][0]:.2f} Y{pts[0][1]:.2f} F9000")
            for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
                e = math.hypot(x1 - x0, y1 - y0) * e_mm
                total_e += e
                lines.append(f"G1 X{x1:.2f} Y{y1:.2f} E{e:.4f} F3000")
        lines.append("G1 E-0.8 F2400")
        lines.append("G1 E0.8 F2400")
    lines += ["M104 S0", "M140 S0", "G28 X"]
    return "\n".join(lines) + "\n"


def sample_broken_stl() -> bytes:
    """Модель с дефектами: дыра, дублирующиеся грани и мелкий осколок."""
    import numpy as np
    import trimesh

    base = trimesh.creation.cylinder(radius=15, height=30, sections=48)
    base = trimesh.util.concatenate([base, trimesh.creation.box((40, 8, 8)).apply_translation([0, 0, 19])])
    faces = base.faces
    keep = np.ones(len(faces), bool)
    keep[5:9] = False  # дыра
    broken = trimesh.Trimesh(base.vertices, np.vstack([faces[keep], faces[:6]]), process=False)
    chip = trimesh.creation.icosphere(subdivisions=1, radius=0.3).apply_translation([30, 30, 2])
    return trimesh.util.concatenate([broken, chip]).export(file_type="stl")


class Demo:
    def __init__(self, db: Database, data_dir: Path):
        self.db = db
        self.data_dir = data_dir
        self.sdcp = SdcpPrinter(ws_port=free_port(), http_port=free_port(), simulate=True)
        self.klipper = MoonrakerPrinter(port=free_port(), simulate=True)

    async def start(self) -> None:
        await self.sdcp.start()
        await self.klipper.start()
        self.db.save_printer(PrinterConfig(
            id="demo-cc", name="Демо: Centauri Carbon", kind="elegoo_sdcp", host="127.0.0.1", port=self.sdcp.ws_port,
            model="Elegoo Centauri Carbon", serial=SdcpPrinter.MBID, build_volume=[256, 256, 256], power_w=150,
            extra={"upload_port": self.sdcp.http_port, "demo": True}))
        self.db.save_printer(PrinterConfig(
            id="demo-n4", name="Демо: Neptune 4 (Klipper)", kind="moonraker", host="127.0.0.1", port=self.klipper.port,
            model="Elegoo Neptune 4 Pro", build_volume=[225, 225, 265], power_w=140, extra={"demo": True}))
        if not self.db.list_library():
            self._seed_library()
        log.info("демо-принтеры запущены")

    def _seed_library(self) -> None:
        lib_dir = self.data_dir / "library"
        for name, content in (("Кубик_20мм_PLA.gcode", sample_gcode().encode()), ("Деталь_с_дефектами.stl", sample_broken_stl())):
            fd, tmp = tempfile.mkstemp(dir=self.data_dir)
            with os.fdopen(fd, "wb") as f:
                f.write(content)
            item: dict[str, Any] = store_upload(tmp, name, lib_dir)
            analysis, thumb = analyze_path(item["stored_path"], item["filename"], [256, 256, 256])
            item.update(kind=analysis["kind"], technology=analysis.get("technology", ""), analysis=analysis, thumbnail=thumb)
            self.db.add_library_item(item)

    async def stop(self) -> None:
        await self.sdcp.stop()
        await self.klipper.stop()
